"""Generates src/payload.py: the PS icon textures, pre-encoded as Xbox 360
tiled DXT5 exactly as buttons.rx2 stores them.

Usage: python tools/build_payload.py [preview_dir]
"""
import base64, os, sys, zlib
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
import gen_icons, dxt5

TEX_BYTES = 0x4000          # 64x64 DXT5 padded to a 32x32-block Xenos tile


def _outer(y, w, l):
    macro = ((y >> 5) * (w >> 5)) << (l + 7)
    micro = ((y & 6) << 2) << l
    return macro + ((micro & ~0xF) << 1) + (micro & 0xF) + ((y & 8) << (3 + l)) + ((y & 1) << 4)


def _inner(x, y, l, base):
    macro = (x >> 5) << (l + 7)
    micro = (x & 7) << l
    off = base + (macro + ((micro & ~0xF) << 1) + (micro & 0xF))
    return ((off & ~0x1FF) << 3) + ((off & 0x1C0) << 2) + (off & 0x3F) + ((y & 16) << 7) + \
        (((((y & 8) >> 2) + (x >> 3)) & 3) << 6)


def xenos_tile(linear, bw=16, bh=16, pitch=32, bpb=16):
    out = bytearray(TEX_BYTES)
    for y in range(bh):
        for x in range(bw):
            s = (y * bw + x) * bpb
            d = (_inner(x, y, 4, _outer(y, pitch, 4)) >> 4) * bpb
            out[d:d + bpb] = linear[s:s + bpb]
    # Xenos endian mode 1 (8-in-16): swap bytes in every 16-bit word
    out[0::2], out[1::2] = out[1::2], out[0::2]
    return bytes(out)


def main():
    preview = sys.argv[1] if len(sys.argv) > 1 else None
    lines = ['# Generated by tools/build_payload.py - do not edit.',
             '# Original PlayStation-style icon art for this mod (not Sony/EA assets).',
             'STYLES = {}']
    for style in gen_icons.STYLES:
        icons = gen_icons.build(style)
        blob = bytearray()
        for idx, im in sorted(icons.items()):
            if preview:
                os.makedirs(os.path.join(preview, style), exist_ok=True)
                im.save(os.path.join(preview, style, f'{gen_icons.NAMES[idx]}.png'))
            blob.append(idx)
            blob += xenos_tile(dxt5.encode(np.array(im)))
        b64 = base64.b64encode(zlib.compress(bytes(blob), 9)).decode()
        lines.append(f'STYLES[{style!r}] = (')
        for k in range(0, len(b64), 100):
            lines.append(f'    {b64[k:k + 100]!r}')
        lines.append(')')
        open(os.path.join(os.path.dirname(__file__), '..', 'go', 'payload', f'{style}.bin'), 'wb').write(zlib.compress(bytes(blob), 9))
    out = os.path.join(os.path.dirname(__file__), '..', 'src', 'payload.py')
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', os.path.normpath(out))


if __name__ == '__main__':
    main()
